BEGIN;
CREATE TEMP TABLE phase1_results(test text,result text) ON COMMIT DROP;
GRANT SELECT,INSERT ON phase1_results TO authenticated;
DO $t$
DECLARE
 gm uuid:='11111111-1111-4111-8111-111111111111';
 player uuid:='22222222-2222-4222-8222-222222222222';
 outsider uuid:='33333333-3333-4333-8333-333333333333';
 room uuid:=gen_random_uuid(); own_token uuid:=gen_random_uuid(); creature uuid:=gen_random_uuid(); other_player uuid:=gen_random_uuid();
 n integer; denied boolean; payload jsonb;
BEGIN
 INSERT INTO public.mesas(id,nome,mestre_id,codigo_convite,cena_ativa,npcs_mesa)
 VALUES(room,'PHASE1 temporary',gm,upper(substr(md5(random()::text),1,6)),
 '[{"data":{"notas":"PRIVATE","config6B":{"d6":8}}}]','[{"data":{"notas":"RESERVE"}}]');
 INSERT INTO public.membros_mesa(mesa_id,usuario_id,cargo) VALUES(room,gm,'mestre'),(room,player,'jogador');
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',gm,'role','authenticated')::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 INSERT INTO public.mesa_tokens(id,mesa_id,owner_type,owner_ref,owner_user_id,display_name)
 VALUES(own_token,room,'player',gen_random_uuid(),player,'Own'),
 (creature,room,'creature',gen_random_uuid(),null,'Hidden creature'),
 (other_player,room,'player',gen_random_uuid(),outsider,'Other player');
 SELECT count(*) INTO n FROM public.mesa_tokens WHERE mesa_id=room AND NOT visible_to_players;
 IF n<>3 THEN RAISE EXCEPTION 'default false falhou'; END IF;
 INSERT INTO phase1_results VALUES('Mestre cria tokens jogador/criatura; default false','PASS — 3 ocultos');
 EXECUTE 'RESET ROLE';
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',outsider,'role','authenticated')::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 denied:=false;
 BEGIN INSERT INTO public.eventos_mesa(mesa_id,usuario_id,tipo,visivel_para,conteudo) VALUES(room,outsider,'mensagem','todos','{}');
 EXCEPTION WHEN insufficient_privilege THEN denied:=true; END;
 IF NOT denied THEN RAISE EXCEPTION 'outsider inseriu evento'; END IF;
 INSERT INTO phase1_results VALUES('Não-membro insere evento próprio','PASS — 42501');
 denied:=false;
 BEGIN PERFORM public.obter_cena_publica(room); EXCEPTION WHEN insufficient_privilege THEN denied:=true; END;
 IF NOT denied THEN RAISE EXCEPTION 'outsider acessou RPC'; END IF;
 SELECT count(*) INTO n FROM public.mesa_tokens WHERE mesa_id=room;
 IF n<>0 THEN RAISE EXCEPTION 'outsider leu token mesmo sem membro'; END IF;
 INSERT INTO phase1_results VALUES('Não-membro: RPC negada e SELECT vazio, mesmo dono de token','PASS');
 EXECUTE 'RESET ROLE';
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',player,'role','authenticated')::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 INSERT INTO public.eventos_mesa(mesa_id,usuario_id,tipo,visivel_para,conteudo) VALUES(room,player,'mensagem','todos','{}');
 INSERT INTO phase1_results VALUES('Membro insere evento','PASS');
 SELECT count(*) INTO n FROM public.obter_cena_publica(room) WHERE token_id=own_token AND is_own;
 IF n<>1 OR (SELECT count(*) FROM public.obter_cena_publica(room))<>1 THEN RAISE EXCEPTION 'RPC revela ocultos ou omite dono'; END IF;
 SELECT count(*) INTO n FROM public.mesa_tokens WHERE mesa_id=room;
 IF n<>1 THEN RAISE EXCEPTION 'SELECT direto revela ocultos'; END IF;
 INSERT INTO phase1_results VALUES('Membro: RPC e SELECT mostram apenas próprio token','PASS — 1 linha');
 denied:=false;
 BEGIN UPDATE public.mesa_tokens SET visible_to_players=true WHERE id=own_token;
 EXCEPTION WHEN insufficient_privilege THEN denied:=true; END;
 IF NOT denied THEN RAISE EXCEPTION 'dono alterou visibilidade'; END IF;
 INSERT INTO phase1_results VALUES('Dono muda própria visibilidade via UPDATE','PASS — 42501');
 denied:=false;
 BEGIN UPDATE public.mesa_tokens SET owner_type='creature',owner_user_id=null WHERE id=own_token;
 EXCEPTION WHEN insufficient_privilege THEN denied:=true; END;
 IF NOT denied THEN RAISE EXCEPTION 'dono alterou identidade'; END IF;
 INSERT INTO phase1_results VALUES('Dono muda identidade para contornar regra','PASS — 42501');
 UPDATE public.mesa_tokens SET visible_to_players=true WHERE id=creature;
 GET DIAGNOSTICS n=ROW_COUNT;
 IF n<>0 THEN RAISE EXCEPTION 'jogador atualizou outro token'; END IF;
 denied:=false;
 BEGIN PERFORM public.definir_visibilidade_token(own_token,true); EXCEPTION WHEN insufficient_privilege THEN denied:=true; END;
 IF NOT denied THEN RAISE EXCEPTION 'RPC visibilidade permitiu jogador'; END IF;
 INSERT INTO phase1_results VALUES('Jogador altera outro token / chama RPC de visibilidade','PASS — 0 linhas / 42501');
 UPDATE public.mesa_tokens SET grid_x=4,grid_y=5,updated_at=now() WHERE id=own_token;
 IF NOT EXISTS(SELECT 1 FROM public.mesa_tokens WHERE id=own_token AND grid_x=4 AND grid_y=5 AND NOT visible_to_players) THEN RAISE EXCEPTION 'movimento dono falhou'; END IF;
 INSERT INTO phase1_results VALUES('Dono movimenta token oculto','PASS');
 SELECT count(*) INTO n FROM public.mesas WHERE id=room;
 IF n<>0 THEN RAISE EXCEPTION 'mesa privada exposta'; END IF;
 SELECT to_jsonb(m) INTO payload FROM public.listar_mesas_acessiveis(room) m;
 IF payload IS NULL OR payload ? 'cena_ativa' OR payload ? 'npcs_mesa' OR payload->>'codigo_convite' IS NOT NULL THEN RAISE EXCEPTION 'metadados vazam'; END IF;
 INSERT INTO phase1_results VALUES('Membro: dados privados de mesas bloqueados; metadados mínimos acessíveis','PASS');
 EXECUTE 'RESET ROLE';
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',gm,'role','authenticated')::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 PERFORM public.definir_visibilidade_token(creature,true);
 IF NOT EXISTS(SELECT 1 FROM public.mesa_tokens WHERE id=creature AND visible_to_players) THEN RAISE EXCEPTION 'revelar falhou'; END IF;
 SELECT count(*) INTO n FROM public.mesa_tokens WHERE mesa_id=room;
 IF n<>3 THEN RAISE EXCEPTION 'mestre perdeu tokens'; END IF;
 IF (SELECT count(*) FROM public.obter_cena_publica(room))<>3 THEN RAISE EXCEPTION 'RPC mestre perdeu tokens'; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.mesas WHERE id=room AND cena_ativa->0->'data'->>'notas'='PRIVATE') THEN RAISE EXCEPTION 'mestre perdeu dados'; END IF;
 UPDATE public.mesa_tokens SET grid_x=8,display_name='Visible creature' WHERE id=creature;
 INSERT INTO phase1_results VALUES('Mestre: revela, lê todos, consulta cena completa e edita token','PASS');
 EXECUTE 'RESET ROLE';
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',player,'role','authenticated')::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 SELECT count(*) INTO n FROM public.obter_cena_publica(room);
 IF n<>2 THEN RAISE EXCEPTION 'criatura revelada ausente'; END IF;
 SELECT to_jsonb(t) INTO payload FROM public.obter_cena_publica(room) t WHERE token_id=creature;
 IF (SELECT count(*) FROM jsonb_object_keys(payload))<>10 OR NOT (payload ? 'iniciativa') OR NOT (payload ? 'visible_to_players') OR payload ? 'data' OR payload ? 'notas' THEN RAISE EXCEPTION 'payload excessivo'; END IF;
 INSERT INTO phase1_results VALUES('Membro após revelar: próprio token + criatura, somente 10 campos públicos (Fase 2)','PASS');
 EXECUTE 'RESET ROLE';
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',gm,'role','authenticated')::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 PERFORM public.definir_visibilidade_token(creature,false);
 EXECUTE 'RESET ROLE';
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',player,'role','authenticated')::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 IF (SELECT count(*) FROM public.obter_cena_publica(room))<>1 OR EXISTS(SELECT 1 FROM public.mesa_tokens WHERE id=creature) THEN RAISE EXCEPTION 'ocultar não removeu'; END IF;
 INSERT INTO phase1_results VALUES('Membro após ocultar: criatura some da RPC e do SELECT','PASS');
 EXECUTE 'RESET ROLE';
 PERFORM set_config('request.jwt.claims','{"role":"anon"}',true);
 EXECUTE 'SET LOCAL ROLE anon';
 denied:=false;
 BEGIN PERFORM public.obter_cena_publica(room); EXCEPTION WHEN insufficient_privilege THEN denied:=true; END;
 EXECUTE 'RESET ROLE';
 IF NOT denied THEN RAISE EXCEPTION 'anon executou RPC'; END IF;
 INSERT INTO phase1_results VALUES('Anon executa RPC pública','PASS — 42501');
 PERFORM set_config('request.jwt.claims',jsonb_build_object('sub',gm,'role','authenticated')::text,true);
 EXECUTE 'SET LOCAL ROLE authenticated';
 DELETE FROM public.mesa_tokens WHERE id=creature;
 GET DIAGNOSTICS n=ROW_COUNT;
 IF n<>1 THEN RAISE EXCEPTION 'mestre perdeu remoção'; END IF;
 INSERT INTO phase1_results VALUES('Mestre remove token','PASS');
 EXECUTE 'RESET ROLE';
END $t$;
SELECT * FROM phase1_results;
ROLLBACK;
